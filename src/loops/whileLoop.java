package loops;

public class whileLoop {
    public static void main(String[] args) {

        // FOR
        for (int i=0; i<=10; i++){
            System.out.println(i);
        }


        //WHILE
        int i=1;
        while(i<=10){
            System.out.println(i);
            i++;
        }


        //DO WHILE
        int x=1;
        do{
            System.out.println(x);
            x++;
        }
        while (x<=10);


    }
}
